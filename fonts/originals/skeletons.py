"""Glyph skeletons for the Vixl Originals: one centreline drawing per character, shared by every stroked family.

Coordinates are nominal font units, y up, on a 1000-unit em: baseline 0, x-height 500, cap height 700,
ascender 750, descender -210. Each family remaps these heights to its own metrics (capitals and figures by the
cap height, lowercase by the x-height), scales x to its width and strokes the result in its own way, so the
drawing here fixes structure, not style.

A stroke is one of:

- ``P("x,y x,y~ ...")``: a polyline. A point ending in ``~`` is a soft corner: each family rounds it with its
  own radius and curve tension, so the same corner is a circle in one face, a squircle in another and a chamfer
  or square in a third. A soft corner uses the whole of an adjacent segment that leads to a sharp point and half
  of one that leads to another soft corner. ``@`` at the start closes the line. ``X``, ``C``, ``A`` and ``D``
  stand for the x-height, cap height, ascender and descender.
- ``O(x0, y0, x1, y1)``: a bowl, the rectangle with four soft corners (an ellipse in a round face).
- ``R(x0, y0, x1, y1, a0, a1)``: part of that bowl, from angle ``a0`` counter-clockwise to ``a1`` (degrees,
  0 pointing right), cut where the ray from the centre crosses it.
- ``dot(x, y)``: a dot, as round or square as the family's dots.

``GLYPHS`` maps each character to ``(case, strokes)``; case ``U`` maps heights by the cap height and ``L`` by
the x-height. ``SQUARE`` holds the double-storey a that faces with squarish bowls use, and ``MONO`` holds the slab-footed alternates monospaced families use for narrow letters. ``BITMAPS``
is the 5 x 9 grid (seven rows above the baseline, two below) the pixel families are built from.
"""

NAMED = {"X": 500, "C": 700, "A": 750, "D": -210, "B": 0}


def _num(token):
    return float(NAMED[token]) if token in NAMED else float(token)


def P(text):
    closed = text.startswith("@")
    nodes = []
    for token in text.lstrip("@").split():
        soft = token.endswith("~")
        x, y = token.rstrip("~").split(",")
        nodes.append((_num(x), _num(y), soft))
    return {"kind": "line", "nodes": nodes, "closed": closed}


def O(x0, y0, x1, y1):
    return {"kind": "bowl", "box": (x0, y0, x1, y1)}


def R(x0, y0, x1, y1, a0, a1):
    return {"kind": "arc", "box": (x0, y0, x1, y1), "angles": (a0, a1)}


def dot(x, y):
    return {"kind": "dot", "at": (x, y)}


